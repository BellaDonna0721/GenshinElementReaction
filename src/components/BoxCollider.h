#pragma once

// =====================================================================
//  BoxCollider —— 轴对齐矩形碰撞体（AABB）
//
//  单一职责：仅存储矩形的宽高，位置由 Transform（中心）决定。
//  与圆形 SphereCollider（radius）并存，互不干扰：
//    · 子弹/敌人/玩家 → 用 SphereCollider（圆）
//    · 墙体          → 用 BoxCollider（矩形）
//  碰撞系统根据实体携带的组件类型自动选择圆-圆 或 圆-矩 算法。
// =====================================================================

struct BoxCollider {
    float width  = 0.0f;  // 矩形宽（沿 X 方向，像素）
    float height = 0.0f;  // 矩形高（沿 Y 方向，像素）
};
