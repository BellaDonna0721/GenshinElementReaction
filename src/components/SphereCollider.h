#pragma once

// =====================================================================
//  SphereCollider —— 球形（圆形）碰撞体
//
//  单一职责：仅存储逻辑碰撞半径。
//  与 BoxCollider（矩形）并存，互不干扰：
//    · 子弹/敌人/玩家 → 用 SphereCollider（圆）
//    · 墙体          → 用 BoxCollider（矩形）
//  碰撞系统根据实体携带的组件类型自动选择圆-圆 或 圆-矩 算法。
//  逻辑碰撞半径可以和视觉渲染半径不同（例如视觉大、判定小更宽容玩家）
// =====================================================================

struct SphereCollider {
    float radius = 0.0f;  //逻辑碰撞半径（像素）
};
