#pragma once

// =====================================================================
//  AttackPower —— 攻击力组件
//
//  单一职责：存储攻击来源的基础伤害数值。
//  挂在：子弹（直射伤害来源）、敌人（接触伤害来源，预留）。
//
//  反应倍率不在此组件计算：增幅反应（蒸发/融化）的倍率由
//  ElementReactionSystem 根据 ReactionType 查表后乘以 base_damage，
//  最终结果写入 DamageEvent.amount。
// =====================================================================

struct AttackPower {
    float base_damage = 10.0f;  // 单次命中的基础伤害（未含反应倍率）
};
