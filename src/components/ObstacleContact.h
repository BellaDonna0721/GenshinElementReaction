#pragma once

// =====================================================================
//  ObstacleContact —— 障碍接触反馈组件（通用，与 AI 行为类型无关）
//  CollisionSystem 统一写入（撞墙/贴边界/敌人互撞），AI 系统下一帧消费后清零。
//  任何需要"被挡后避让"能力的实体挂载此组件即可，新增 AI 类型零改动。
//
//  block_push 契约（重要）：
//    每个碰撞来源写入【单位法向】（障碍→自身），多来源累加成向量和；
//    消费方取方向时必须再归一化一次（累加后不再是单位向量）。
//    模长仅反映多来源的同向/反向程度，不代表穿透深度——
//    物理推到位移在 CollisionSystem 内用带模长的 MTV 完成，与本字段解耦。
//    这样所有来源量纲一致，避免"深穿透来源在累加中隐性占更大权重"。
// =====================================================================
struct ObstacleContact {
    bool  blocked      = false;  // 上一帧被障碍阻挡
    float block_push_x = 0.0f;   // 推开方向 X（单位法向累加，消费时归一化）
    float block_push_y = 0.0f;   // 推开方向 Y（单位法向累加，消费时归一化）
};
